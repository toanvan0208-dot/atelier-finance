function buildLesson(base: (typeof baseLessons)[number]) {
  return {
    ...base,
    relatedModules: [...base.relatedModules],
    goal: `Giúp người dùng dùng kiến thức này trong ${base.relatedModules.join(", ")} mà không kết luận vội.`,
    plainExplanation:
      base.id === "pe-cyclical-trap"
        ? "Với ngành chu kỳ, lợi nhuận có thể tăng mạnh ở đỉnh chu kỳ. Khi mẫu số đang cao bất thường, P/E nhìn thấp nhưng không chắc là rẻ."
        : "Hãy xem khái niệm này như một câu hỏi kiểm tra dữ liệu. Nó không thay bạn quyết định, chỉ giúp bạn biết cần nhìn điểm nào tiếp theo.",
    realExample:
      base.id === "profit-vs-cashflow"
        ? "Một doanh nghiệp báo lợi nhuận tăng nhưng tiền chưa thu được vì khoản phải thu tăng nhanh. Khi đó cần xem dòng tiền kinh doanh."
        : "Khi một cổ phiếu hoặc ngành có vẻ hấp dẫn, bài học này giúp bạn hỏi lại: dữ liệu nào xác nhận, dữ liệu nào có thể phủ định?",
    dataToCheck:
      base.id === "pe-cyclical-trap"
        ? ["Lợi nhuận hiện tại", "Biên lợi nhuận gộp", "Giá đầu ra", "Giá nguyên liệu", "Tồn kho", "Pha chu kỳ ngành"]
        : ["Nguồn dữ liệu", "Xu hướng 3-5 kỳ", "So sánh ngành", "Dữ liệu xác nhận", "Dữ liệu phủ định"],
    commonMistake:
      base.id === "value-trap"
        ? "Thấy P/E thấp rồi kết luận cổ phiếu đang rẻ."
        : base.id === "profit-vs-cashflow"
          ? "Thấy lợi nhuận tăng rồi nghĩ doanh nghiệp chắc chắn khỏe."
          : "Nhìn một dữ liệu đơn lẻ rồi kết luận quá nhanh.",
    linkedModules: [...base.relatedModules],
    quiz: {
      question:
        base.id === "pe-cyclical-trap"
          ? "P/E thấp ở ngành chu kỳ có luôn là dấu hiệu hấp dẫn không?"
          : `Sau bài "${base.title}", bạn nên làm gì trước khi kết luận?`,
      answer:
        base.id === "pe-cyclical-trap"
          ? "Không. Cần kiểm tra lợi nhuận có đang ở đỉnh chu kỳ không."
          : "Cần quay lại module liên quan để kiểm tra dữ liệu xác nhận, dữ liệu phủ định và rủi ro chính.",
    },
    miniCase: {
      prompt:
        base.id === "profit-vs-cashflow"
          ? "Doanh thu tăng 25%, lợi nhuận tăng 20%, nhưng CFO âm và khoản phải thu tăng mạnh. Bạn kiểm tra gì?"
          : "Một dữ liệu nhìn có vẻ thuận lợi, nhưng bạn chưa kiểm tra module liên quan. Bạn có kết luận ngay không?",
      goodAnswer:
        base.id === "profit-vs-cashflow"
          ? "Kiểm tra khoản phải thu, tồn kho, chất lượng doanh thu và dòng tiền kinh doanh."
          : "Không kết luận ngay. Cần kiểm chứng thêm bằng module liên quan và ghi rõ giả thuyết cần kiểm tra.",
    },
    outcome:
      "Người dùng biết quay lại module phân tích liên quan để tự hoàn thiện nhận định, không xem bài học như lời khuyên hành động.",
  };
}

